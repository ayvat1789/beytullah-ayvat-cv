let currentLang = 'en';
let chatHistory = [];
let isSending = false;

const chatMessagesEl = document.getElementById('chatMessages');
const chatFormEl = document.getElementById('chatForm');
const chatInputEl = document.getElementById('chatInput');
const chatSendEl = document.getElementById('chatSend');
const langToggleEl = document.getElementById('langToggle');
const themeToggleEl = document.getElementById('themeToggle');
const clearChatEl = document.getElementById('clearChat');
const printBtnEl = document.getElementById('printBtn');
const openChatHeroEl = document.getElementById('openChatHero');
const mobileChatFabEl = document.getElementById('mobileChatFab');
const chatPanelEl = document.getElementById('chatPanel');

document.getElementById('year').textContent = new Date().getFullYear();

function appendMessage(role, text, extraClass = '') {
  const bubble = document.createElement('div');
  bubble.className = `msg msg-${role} ${extraClass}`.trim();
  bubble.textContent = text;
  chatMessagesEl.appendChild(bubble);
  chatMessagesEl.scrollTop = chatMessagesEl.scrollHeight;
  return bubble;
}

function appendTypingIndicator() {
  const bubble = document.createElement('div');
  bubble.className = 'msg msg-assistant';
  bubble.innerHTML = '<div class="typing"><span></span><span></span><span></span></div>';
  chatMessagesEl.appendChild(bubble);
  chatMessagesEl.scrollTop = chatMessagesEl.scrollHeight;
  return bubble;
}

function resetChat() {
  chatHistory = [];
  chatMessagesEl.innerHTML = '';
  appendMessage('assistant', TRANSLATIONS[currentLang].welcomeMessage);
}

function applyLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;
  langToggleEl.textContent = lang === 'en' ? 'TR' : 'EN';

  const dict = TRANSLATIONS[lang];
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) el.textContent = dict[key];
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) el.setAttribute('placeholder', dict[key]);
  });

  if (chatHistory.length === 0) {
    resetChat();
  }
}

async function sendMessage(text) {
  const trimmed = text.trim();
  if (!trimmed || isSending) return;

  isSending = true;
  chatSendEl.disabled = true;
  chatInputEl.value = '';

  appendMessage('user', trimmed);
  chatHistory.push({ role: 'user', content: trimmed });

  const loadingBubble = appendTypingIndicator();

  try {
    const response = await fetch('/api/chat', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ messages: chatHistory.slice(-10) })
    });

    const data = await response.json().catch(() => ({}));
    loadingBubble.remove();

    if (!response.ok || !data.reply) {
      appendMessage(
        'assistant',
        data.error ||
          (currentLang === 'tr'
            ? 'Şu an yanıt alınamadı, lütfen biraz sonra tekrar deneyin.'
            : 'Could not reach the AI assistant right now. Please try again shortly.'),
        'msg-error'
      );
      chatHistory.pop();
    } else {
      appendMessage('assistant', data.reply);
      chatHistory.push({ role: 'assistant', content: data.reply });
    }
  } catch (_err) {
    loadingBubble.remove();
    appendMessage(
      'assistant',
      currentLang === 'tr'
        ? 'Bağlantı hatası oluştu. Lütfen tekrar deneyin.'
        : 'Connection error. Please try again.',
      'msg-error'
    );
    chatHistory.pop();
  } finally {
    isSending = false;
    chatSendEl.disabled = false;
    chatInputEl.focus();
  }
}

chatFormEl.addEventListener('submit', (e) => {
  e.preventDefault();
  sendMessage(chatInputEl.value);
});

document.querySelectorAll('.chip').forEach((chip) => {
  chip.addEventListener('click', () => {
    const prompt = currentLang === 'tr' ? chip.dataset.promptTr : chip.dataset.promptEn;
    sendMessage(prompt);
  });
});

clearChatEl.addEventListener('click', resetChat);

langToggleEl.addEventListener('click', () => {
  applyLanguage(currentLang === 'en' ? 'tr' : 'en');
});

themeToggleEl.addEventListener('click', () => {
  const next = document.documentElement.getAttribute('data-theme') === 'dark' ? 'light' : 'dark';
  document.documentElement.setAttribute('data-theme', next);
  localStorage.setItem('cv-theme', next);
});

printBtnEl.addEventListener('click', () => window.print());

function focusChat() {
  chatPanelEl.scrollIntoView({ behavior: 'smooth', block: 'center' });
  setTimeout(() => chatInputEl.focus(), 350);
}

openChatHeroEl.addEventListener('click', focusChat);
mobileChatFabEl.addEventListener('click', focusChat);

// Initialize theme & language
const savedTheme = localStorage.getItem('cv-theme');
if (savedTheme === 'dark' || savedTheme === 'light') {
  document.documentElement.setAttribute('data-theme', savedTheme);
}
applyLanguage('en');
